create table
  public.predictions (
    id bigint generated by default as identity,
    created_at timestamp with time zone not null default now(),
    bulletin_id text not null,
    match_id smallint not null,
    match_name text not null,
    prediction text not null,
    analysis_text text null,
    status text not null default 'pending'::text,
    constraint predictions_pkey primary key (id),
    constraint predictions_bulletin_id_match_id_key unique (bulletin_id, match_id)
  ) tablespace pg_default;

-- RLS Policies
alter table public.predictions enable row level security;

-- Allow read access for all users
create policy "Allow read access on predictions" on public.predictions for select using (true);